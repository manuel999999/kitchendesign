namespace Melcher
{
    /// <summary>
    ///     The supported types of toe kicks.
    /// </summary>
    public enum CabinetToeKickType
    {
        /// <summary>
        ///     No toe kick will be rendered on the cabinet.
        /// </summary>
        None,

        /// <summary>
        ///     The toe kick is inset under the cabinet.
        /// </summary>
        Inset,

        /// <summary>
        ///     The toe kick is flush with the cabinet.
        /// </summary>
        Flush
    }   // enum CabinetToeKickType

}   // namespace Melcher

