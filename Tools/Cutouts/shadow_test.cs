var mat = UnityEditor.AssetDatabase.LoadAssetAtPath<UnityEngine.Material>("__MAT__");
var root = UnityEngine.GameObject.Find("CutoutShadowTest");
if (root != null) UnityEngine.Object.Destroy(root);
root = new UnityEngine.GameObject("CutoutShadowTest");
var origin = new UnityEngine.Vector3(-6f, 0f, 100f);
root.transform.position = origin;
var plate = UnityEngine.GameObject.CreatePrimitive(UnityEngine.PrimitiveType.Cube);
plate.name = "Plate";
plate.transform.SetParent(root.transform, false);
plate.transform.localPosition = new UnityEngine.Vector3(0f, 1.2f, 0f);
plate.transform.localScale = new UnityEngine.Vector3(1.5f, 0.1f, 1.5f);
var mr = plate.GetComponent<UnityEngine.MeshRenderer>();
mr.sharedMaterial = mat;
mr.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.On;
KitchenDesign.Cutouts.CutoutClipSet.SetRendererSlot(mr, __SLOT__);
var floor = UnityEngine.GameObject.CreatePrimitive(UnityEngine.PrimitiveType.Cube);
floor.name = "Floor";
floor.transform.SetParent(root.transform, false);
floor.transform.localPosition = new UnityEngine.Vector3(0f, 0.01f, 0f);
floor.transform.localScale = new UnityEngine.Vector3(4f, 0.02f, 4f);
floor.GetComponent<UnityEngine.MeshRenderer>().sharedMaterial = mat;
var hole = new UnityEngine.GameObject("HoleSpace");
hole.transform.SetParent(root.transform, false);
hole.transform.localPosition = new UnityEngine.Vector3(0f, 1.2f, 0f);
var set = new KitchenDesign.Cutouts.CutoutClipSet();
set.AddBox(30, hole.transform, new UnityEngine.Bounds(UnityEngine.Vector3.zero, new UnityEngine.Vector3(0.5f, 0.5f, 0.5f)), KitchenDesign.Shared.Enums.CutoutFaces.None);
set.Apply();
UnityEngine.Light sun = null;
foreach (var l in UnityEngine.Object.FindObjectsByType<UnityEngine.Light>(UnityEngine.FindObjectsSortMode.None)) if (l.type == UnityEngine.LightType.Directional) sun = l;
var go = UnityEngine.GameObject.Find("CutoutTestCam");
go.transform.position = origin + new UnityEngine.Vector3(0f, 6f, -0.01f);
go.transform.rotation = UnityEngine.Quaternion.LookRotation(UnityEngine.Vector3.down, UnityEngine.Vector3.forward);
return "sun=" + (sun ? sun.name + " shadows=" + sun.shadows + " dir=" + sun.transform.forward.ToString("F2") : "none") + " slot=" + __SLOT__;
